// 换电脑 / 换 Wi-Fi 后：把新地址加到列表最前面即可。
// 临时覆盖（开发者工具 Console 或真机调试 Console 里执行）：
//   wx.setStorageSync('baseUrl', 'http://192.168.1.4:8000/')
// 清掉缓存恢复自动探测：
//   wx.removeStorageSync('baseUrl')
// ============================================================
